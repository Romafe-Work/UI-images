const limpo = new Map<string, string>();
/** O ícone pelo nome do Lucide, decorativo (aria-hidden), com uma classe opcional. */
export function ic(nome: string, cls = ''): string {
  let s = limpo.get(nome);
  if (!s) {
    s = (RAW[nome] || RAW['circle-dot']).replace(/<!--[\s\S]*?-->/, '').replace(/\s+class="lucide lucide-([^"]*)"/, ' data-lucide="$1"').replace(/\s+class="[^"]*"/, '').replace(/\n\s*/g, '');
    limpo.set(nome, s);
  }
  return s.replace('<svg', `<svg${cls ? ` class="${cls}"` : ''} aria-hidden="true"`);
}
